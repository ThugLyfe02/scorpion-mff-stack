"""Consume the research desk's context - as facts, and only for attribution.

The stock-finder exports `scorpion.research-context.v1`. This module verifies that
contract independently (schema, authority, identity, checksum), then joins closed
trades to the snapshot by symbol and ET session date.

It deliberately does **not** size anything. The scanner is research-only; a broken or
malicious snapshot must not be able to shrink, delay, or block an MFF order. The join
answers one research question:

    do hone trades on names the desk flagged as buyout-at-deal / halt / dilution /
    FADE underperform the rest of the record?

That is useful without giving the scanner authority over the money path. The
canonicalisation matches the producer byte-for-byte; the fixture in
`tests/fixtures/research-context-2026-09-11.json` is generated by the producer and
pinned by both repos.
"""

from __future__ import annotations

import hashlib
import json
import time
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from .evidence import Trade, bayesian_p_up, bootstrap_mean, mean

SCHEMA = "scorpion.research-context.v1"
AUTHORITY = "RESEARCH_ONLY"
ET_OFFSET_S = -4 * 3600
FLAG_NAMES = ("buyout_at_deal", "halt_risk", "dilution_risk")
TAPE_VALUES = {"GO", "MIXED", "FADE", "UNKNOWN"}
DISPOSITIONS = {"GO", "MIXED", "SKIP", "CONTEXT", "UNKNOWN"}


class ContextError(ValueError):
    """The snapshot cannot be trusted. It is optional context, never a blocker."""


def _canonical(payload: Mapping[str, object]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def checksum_for(payload: Mapping[str, object]) -> str:
    material = {k: v for k, v in payload.items() if k != "checksum"}
    return hashlib.sha256(_canonical(material).encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class SymbolContext:
    symbol: str
    instrument_id: str
    disposition: str
    tape_flag: str
    buyout_at_deal: bool
    halt_risk: bool
    dilution_risk: bool
    catalyst: str = ""
    quality_blockers: tuple[str, ...] = ()

    def flag(self, name: str) -> bool:
        return bool(getattr(self, name))

    def to_dict(self) -> dict:
        return {"symbol": self.symbol, "disposition": self.disposition,
                "tape_flag": self.tape_flag, "buyout_at_deal": self.buyout_at_deal,
                "halt_risk": self.halt_risk, "dilution_risk": self.dilution_risk}


@dataclass(frozen=True)
class ResearchContext:
    as_of: str
    generated_at_utc: str
    checksum: str
    producer: Mapping[str, object]
    symbols: Mapping[str, SymbolContext] = field(default_factory=dict)

    @property
    def count(self) -> int:
        return len(self.symbols)

    def get(self, symbol: str) -> SymbolContext | None:
        return self.symbols.get((symbol or "").strip().upper())

    def to_dict(self) -> dict:
        return {"as_of": self.as_of, "generated_at_utc": self.generated_at_utc,
                "checksum": self.checksum, "producer": dict(self.producer),
                "symbols": [row.to_dict() for row in self.symbols.values()]}


def _required(payload: Mapping[str, object], key: str) -> str:
    value = payload.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ContextError(f"{key} is required")
    return value.strip()


def verify(payload: Mapping[str, object]) -> ResearchContext:
    """Validate the producer's contract. Fail closed, naming the violation."""
    if not isinstance(payload, Mapping):
        raise ContextError("context must be an object")
    if payload.get("schema") != SCHEMA:
        raise ContextError(f"schema must be {SCHEMA}")
    if payload.get("authority") != AUTHORITY:
        raise ContextError(f"authority must be {AUTHORITY}")
    expected = checksum_for(payload)
    if payload.get("checksum") != expected:
        raise ContextError("checksum mismatch: the snapshot was modified after export")
    as_of = _required(payload, "as_of")
    generated = _required(payload, "generated_at_utc")
    try:
        datetime.strptime(as_of, "%Y-%m-%d")
    except ValueError:
        raise ContextError("as_of must be YYYY-MM-DD") from None
    try:
        iso = generated[:-1] + "+00:00" if generated.endswith("Z") else generated
        stamp = datetime.fromisoformat(iso)
    except ValueError:
        raise ContextError("generated_at_utc must be ISO-8601") from None
    if stamp.tzinfo is None or stamp.utcoffset() is None:
        raise ContextError("generated_at_utc must be timezone-aware")
    if stamp.date().isoformat() != as_of:
        raise ContextError("generated_at_utc must fall on as_of")
    producer = payload.get("producer")
    if not isinstance(producer, Mapping):
        raise ContextError("producer must be an object")
    rows = payload.get("symbols")
    if not isinstance(rows, list) or not rows:
        raise ContextError("symbols must be a non-empty array")

    symbols: dict[str, SymbolContext] = {}
    for row in rows:
        if not isinstance(row, Mapping):
            raise ContextError("each symbol row must be an object")
        symbol = _required(row, "symbol").upper()
        if symbol in symbols:
            raise ContextError(f"duplicate symbol {symbol}")
        if row.get("instrument_id") != f"US_EQUITY:{symbol}":
            raise ContextError(f"{symbol}: instrument_id must be US_EQUITY:{symbol}")
        disposition = str(row.get("disposition") or "")
        if disposition not in DISPOSITIONS:
            raise ContextError(f"{symbol}: invalid disposition")
        tape = str(row.get("tape_flag") or "")
        if tape not in TAPE_VALUES:
            raise ContextError(f"{symbol}: invalid tape_flag")
        for name in FLAG_NAMES:
            if not isinstance(row.get(name), bool):
                raise ContextError(f"{symbol}: {name} must be boolean")
        quality = row.get("quality")
        blockers: tuple[str, ...] = ()
        if isinstance(quality, Mapping):
            raw = quality.get("blocking_reasons") or []
            if not isinstance(raw, (list, tuple)) or not all(isinstance(x, str) for x in raw):
                raise ContextError(f"{symbol}: quality.blocking_reasons must be strings")
            blockers = tuple(raw)
        symbols[symbol] = SymbolContext(
            symbol=symbol, instrument_id=str(row["instrument_id"]),
            disposition=disposition, tape_flag=tape,
            buyout_at_deal=bool(row["buyout_at_deal"]),
            halt_risk=bool(row["halt_risk"]),
            dilution_risk=bool(row["dilution_risk"]),
            catalyst=str(row.get("catalyst") or ""),
            quality_blockers=blockers)
    return ResearchContext(as_of=as_of, generated_at_utc=generated,
                           checksum=str(payload["checksum"]), producer=producer,
                           symbols=symbols)


def load(path: str | Path) -> ResearchContext:
    p = Path(path)
    try:
        payload = json.loads(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ContextError(f"context not found: {p}") from None
    except (OSError, json.JSONDecodeError) as exc:
        raise ContextError(f"cannot read context at {p}: {exc}") from None
    return verify(payload)


def et_date(ts: float) -> str:
    """ET session date from an epoch timestamp (fixed UTC-04:00, like the governor)."""
    return time.strftime("%Y-%m-%d", time.gmtime(ts + ET_OFFSET_S))


@dataclass
class FlagGroup:
    name: str
    value: str
    n: int
    mean_usd: float
    ci_low: float
    ci_high: float
    posterior_up: float

    def to_dict(self) -> dict:
        return {"name": self.name, "value": self.value, "n": self.n,
                "mean_usd": round(self.mean_usd, 2),
                "ci_low_usd": round(self.ci_low, 2),
                "ci_high_usd": round(self.ci_high, 2),
                "posterior_p_up": round(self.posterior_up, 4)}


@dataclass
class Attribution:
    as_of: str
    matched: int
    unmatched: int
    groups: list[FlagGroup] = field(default_factory=list)
    context_symbols: int = 0

    def to_dict(self) -> dict:
        return {"as_of": self.as_of, "matched": self.matched,
                "unmatched": self.unmatched, "context_symbols": self.context_symbols,
                "groups": [g.to_dict() for g in self.groups]}


def attribute(trades: Iterable[Trade], context: ResearchContext, *,
              seed: int = 7) -> Attribution:
    """Join trades to the snapshot by symbol and ET date, then group by flag."""
    buckets: dict[tuple[str, str], list[float]] = {}
    matched = 0
    unmatched = 0
    for trade in trades:
        if et_date(trade.ts) != context.as_of:
            unmatched += 1
            continue
        row = context.get(trade.ticker)
        if row is None or row.disposition == "CONTEXT":
            # A mega-cap / out-of-box row is context, not a candidate. Joining a
            # trade to it would read a research note as a selection.
            unmatched += 1
            continue
        matched += 1
        for name in FLAG_NAMES:
            if row.flag(name):
                buckets.setdefault((name, "true"), []).append(trade.pnl_usd)
        if row.tape_flag in {"FADE", "GO", "MIXED"}:
            buckets.setdefault(("tape_flag", row.tape_flag), []).append(trade.pnl_usd)

    groups: list[FlagGroup] = []
    for (name, value), xs in sorted(buckets.items()):
        boot = bootstrap_mean(xs, draws=800, seed=seed)
        groups.append(FlagGroup(name=name, value=value, n=len(xs), mean_usd=mean(xs),
                                ci_low=boot.low, ci_high=boot.high,
                                posterior_up=bayesian_p_up(xs, draws=800, seed=seed + 1)))
    return Attribution(as_of=context.as_of, matched=matched, unmatched=unmatched,
                       groups=groups, context_symbols=context.count)


def attribution_text(attr: Attribution) -> str:
    lines = [
        (f"scanner context | {attr.as_of} | {attr.context_symbols} symbols | "
         f"matched {attr.matched} trade(s), unmatched {attr.unmatched}"),
    ]
    if not attr.groups:
        lines.append("  no overlapping symbol carried a flag or a tape call on this day")
        return "\n".join(lines)
    lines.append("  group                 n      mean$       95% CI              P(up)")
    for group in attr.groups:
        lines.append(
            f"  {group.name + '=' + group.value:<20}{group.n:>3}  "
            f"{group.mean_usd:>10,.2f}  "
            f"[{group.ci_low:>9,.2f},{group.ci_high:>9,.2f}]  {group.posterior_up:>5.1%}")
    lines.append("  research attribution only: this does not size or gate an order")
    return "\n".join(lines)
